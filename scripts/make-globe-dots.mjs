// Turns Natural Earth 1:110m land (world-atlas land-110m.json, TopoJSON) into evenly spaced
// [lat, lng] dots, split into Africa and the rest of the world. Writes the site's globe data file.
//
//   curl -L -o /tmp/land-110m.json https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json
//   node scripts/make-globe-dots.mjs /tmp/land-110m.json app/components/globe/world.ts
import { readFileSync, writeFileSync } from "node:fs";

const [, , input, output] = process.argv;
const topo = JSON.parse(readFileSync(input, "utf8"));
const { scale, translate } = topo.transform;

// Decode the delta-encoded arcs into absolute [lng, lat] points.
const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => {
    x += dx; y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});
const arcPoints = (i) => (i >= 0 ? arcs[i] : arcs[~i].slice().reverse());
const ring = (ids) => ids.flatMap((i, k) => (k === 0 ? arcPoints(i) : arcPoints(i).slice(1)));

// Every polygon as a list of rings (outer first, then holes).
const polygons = [];
for (const geom of topo.objects.land.geometries) {
  const polys = geom.type === "Polygon" ? [geom.arcs] : geom.arcs;
  for (const p of polys) polygons.push(p.map(ring));
}

// Bounding boxes make the point-in-polygon test fast.
const boxes = polygons.map((rings) => {
  let x0 = 180, x1 = -180, y0 = 90, y1 = -90;
  for (const [x, y] of rings[0]) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  return [x0, x1, y0, y1];
});

const inRing = (lng, lat, r) => {
  let inside = false;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [xi, yi] = r[i], [xj, yj] = r[j];
    if ((yi > lat) !== (yj > lat) && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
const onLand = (lng, lat) =>
  polygons.some((rings, k) => {
    const [x0, x1, y0, y1] = boxes[k];
    if (lng < x0 || lng > x1 || lat < y0 || lat > y1) return false;
    return inRing(lng, lat, rings[0]) && !rings.slice(1).some((h) => inRing(lng, lat, h));
  });

// Africa: the continent's box, minus Europe (north of ~37.5°) and Arabia/the Levant
// (east of a line along the Red Sea, from Bab-el-Mandeb to Suez).
const redSea = (lat) => 43.4 + ((lat - 12.5) * (32.6 - 43.4)) / (30 - 12.5);
const isAfrica = (lng, lat) => lat >= -36 && lat <= 37.6 && lng >= -26 && lng <= 52 && !(lat > 12 && lng > redSea(lat));

// Evenly spaced: the longitude step widens towards the poles. Antarctica is left out.
const STEP = 1.6;
const africa = [], world = [];
for (let lat = 82; lat >= -58; lat -= STEP) {
  const step = STEP / Math.max(0.2, Math.cos((lat * Math.PI) / 180));
  const offset = (Math.round(lat / STEP) % 2) * (step / 2);
  for (let lng = -180 + offset; lng < 180; lng += step) {
    if (!onLand(lng, lat)) continue;
    const pt = [Math.round(lat * 10) / 10, Math.round(lng * 10) / 10];
    (isAfrica(lng, lat) ? africa : world).push(...pt);
  }
}

const rows = (arr) => {
  const out = [];
  for (let i = 0; i < arr.length; i += 24) out.push("  " + arr.slice(i, i + 24).join(", ") + ",");
  return out.join("\n");
};
writeFileSync(
  output,
  `// Land as [lat, lng] pairs, about ${STEP}° apart, from Natural Earth 1:110m land (public domain, via the
// world-atlas package). Africa is split out so it can be drawn in brand blue. Antarctica is left out.
// Generated by scripts/make-globe-dots.mjs; don't edit by hand.
export const AFRICA: number[] = [\n${rows(africa)}\n];\n\nexport const WORLD: number[] = [\n${rows(world)}\n];\n`,
);
console.log({ africa: africa.length / 2, world: world.length / 2 });
